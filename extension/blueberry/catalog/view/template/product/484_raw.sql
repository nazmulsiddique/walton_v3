	CC.SERVICE_CENTER_ID,
	O.HRMS_ORG_TITLE AS TITLE,
	COUNT(*) AS WORK_PENDING,
	ROW_NUMBER() OVER (
	ORDER BY COUNT(*) ASC) AS RN
