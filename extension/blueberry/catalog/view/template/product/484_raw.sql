SELECT
	/* DELIVERY PENDING */
	DP.TITLE AS DELIVERY_PENDING_TITLE,
	DP.DELIVERY_PENDING AS DELIVERY_PENDING_TOTAL,
	DP_DATE.DELIVERY_PENDING AS DELIVERY_PENDING_DATE_WISE,
	NVL(RC_DEL.RECEIVED, 0) AS DELIVERY_PENDING_RECEIVED_QTY,
	/* RECEIVED */
	RC.TITLE AS RECEIVED_TITLE,
	RC.RECEIVED AS RECEIVED_TOTAL,
	/* WORK DONE */
	WD.TITLE AS WORK_DONE_TITLE,
	WD.WORK_DONE AS WORK_DONE_TOTAL,
	WD_DATE.WORK_DONE AS WORK_DONE_DATE_WISE,
	NVL(RC_WD.RECEIVED, 0) AS WORK_DONE_RECEIVED_QTY,
	/* WORK PENDING */
	WP.TITLE AS WORK_PENDING_TITLE,
	WP.WORK_PENDING AS WORK_PENDING_TOTAL,
	WP_DATE.WORK_PENDING AS WORK_PENDING_DATE_WISE,
	NVL(RC_WP.RECEIVED, 0) AS WORK_PENDING_RECEIVED_QTY
FROM
	DELIVERY_PENDING_CTE DP
LEFT JOIN DELIVERY_PENDING_CTE_DATE DP_DATE
       ON
	DP.SERVICE_CENTER_ID = DP_DATE.SERVICE_CENTER_ID
LEFT JOIN RECEIVED_CTE RC_DEL
       ON
	DP.SERVICE_CENTER_ID = RC_DEL.SERVICE_CENTER_ID
LEFT JOIN RECEIVED_CTE RC
       ON
	RC.RN = DP.RN
	AND RC.RN <= 10
LEFT JOIN WORK_DONE_CTE WD
       ON
	DP.RN = WD.RN
LEFT JOIN WORK_DONE_CTE_DATE WD_DATE
       ON
	WD.SERVICE_CENTER_ID = WD_DATE.SERVICE_CENTER_ID
LEFT JOIN RECEIVED_CTE RC_WD
       ON
	WD.SERVICE_CENTER_ID = RC_WD.SERVICE_CENTER_ID
LEFT JOIN WORK_PENDING_CTE WP
       ON
	DP.RN = WP.RN
LEFT JOIN WORK_PENDING_CTE_DATE WP_DATE
       ON
	WP.SERVICE_CENTER_ID = WP_DATE.SERVICE_CENTER_ID
LEFT JOIN RECEIVED_CTE RC_WP
       ON
	WP.SERVICE_CENTER_ID = RC_WP.SERVICE_CENTER_ID
WHERE
	DP.RN <= 10
ORDER BY
	DP.RN