WITH ORG_ACTIVE AS (
SELECT
	/*+ INDEX(O IDX_ORG_ACTIVE) */
	HRMS_ORGID,
	HRMS_ORG_TITLE
FROM
	CRM.ORG_MAP O
WHERE
	O.IS_ACTIVE = 1
	AND O.IS_LIVE <> 0
	AND O.COUNTRY IS NULL
	AND O.HRMS_ORGID <> 563
        
),

/* ===========================
   DELIVERY PENDING (TOTAL)
   =========================== */
DELIVERY_PENDING_CTE AS (
SELECT
	CC.SERVICE_CENTER_ID,
	O.HRMS_ORG_TITLE AS TITLE,
	COUNT(*) AS DELIVERY_PENDING,
	ROW_NUMBER() OVER (
	ORDER BY COUNT(*) ASC) AS RN
FROM
	CRM.CUSTOMER_COMPLAINS CC
JOIN ORG_ACTIVE O ON
	O.HRMS_ORGID = CC.SERVICE_CENTER_ID
WHERE
	NVL(CC.TRANSFER_TYPE, 0) NOT IN ('REPLACEMENT_TRANSFER', 'LONG_TIME_UNDELIVERED')
		AND CC.ALKP_COMPLAIN_LEVEL_ID = 26
		AND CC.PRODUCT_GROUP = NVL('', CC.PRODUCT_GROUP)
	GROUP BY
		CC.SERVICE_CENTER_ID,
		O.HRMS_ORG_TITLE
),

/* ===========================
   DELIVERY PENDING (DATE-WISE)
   =========================== */
DELIVERY_PENDING_CTE_DATE AS (
SELECT
	CC.SERVICE_CENTER_ID,
	O.HRMS_ORG_TITLE AS TITLE,
	COUNT(*) AS DELIVERY_PENDING,
	ROW_NUMBER() OVER (
	ORDER BY COUNT(*) ASC) AS RN
FROM
	CRM.CUSTOMER_COMPLAINS CC
JOIN ORG_ACTIVE O ON
	O.HRMS_ORGID = CC.SERVICE_CENTER_ID
WHERE
	NVL(CC.TRANSFER_TYPE, 0) NOT IN ('REPLACEMENT_TRANSFER', 'LONG_TIME_UNDELIVERED')
		AND CC.ALKP_COMPLAIN_LEVEL_ID = 26
		AND CC.PRODUCT_GROUP = NVL('', CC.PRODUCT_GROUP)
			AND TRUNC(CC.CREATED_DATE) BETWEEN '01-NOV-2025' AND '19-NOV-2025'
		GROUP BY
			CC.SERVICE_CENTER_ID,
			O.HRMS_ORG_TITLE
),

/* ===========================
   RECEIVED CTE
   =========================== */
RECEIVED_CTE AS (
SELECT
	CC.SERVICE_CENTER_ID,
	O.HRMS_ORG_TITLE AS TITLE,
	COUNT(*) AS RECEIVED,
	ROW_NUMBER() OVER (
	ORDER BY COUNT(*) ASC) AS RN
FROM
	CRM.CUSTOMER_COMPLAINS CC
JOIN ORG_ACTIVE O ON
	O.HRMS_ORGID = CC.SERVICE_CENTER_ID
WHERE
	NVL(CC.TRANSFER_TYPE, 0) NOT IN ('REPLACEMENT_TRANSFER', 'LONG_TIME_UNDELIVERED')
		AND CC.ALKP_COMPLAIN_LEVEL_ID IN (22, 25, 26, 27, 28, 29)
			AND CC.PRODUCT_GROUP = NVL('', CC.PRODUCT_GROUP)
				AND TRUNC(CC.CREATED_DATE) BETWEEN '01-NOV-2025' AND '19-NOV-2025'
			GROUP BY
				CC.SERVICE_CENTER_ID,
				O.HRMS_ORG_TITLE
),

/* ===========================
   WORK DONE (TOTAL)
   =========================== */
WORK_DONE_CTE AS (
SELECT
	CC.SERVICE_CENTER_ID,
	O.HRMS_ORG_TITLE AS TITLE,
	COUNT(*) AS WORK_DONE,
	ROW_NUMBER() OVER (
	ORDER BY COUNT(*) ASC) AS RN
FROM
	CRM.CUSTOMER_COMPLAINS CC
JOIN ORG_ACTIVE O ON
	O.HRMS_ORGID = CC.SERVICE_CENTER_ID
JOIN CRM.JOBS J ON
	J.CUST_COMPLAIN_ID = CC.ID
	AND J.ID = (
	SELECT
		MAX(ID)
	FROM
		CRM.JOBS
	WHERE
		CUST_COMPLAIN_ID = CC.ID)
WHERE
	NVL(CC.TRANSFER_TYPE, 0) NOT IN ('REPLACEMENT_TRANSFER', 'LONG_TIME_UNDELIVERED')
		AND CC.ALKP_COMPLAIN_LEVEL_ID IN (26, 27)
			AND CC.PRODUCT_GROUP = NVL('', CC.PRODUCT_GROUP)
				AND TRUNC(NVL(J.QC_END_DATE, J.QC_START_DATE)) BETWEEN '01-NOV-2025' AND '19-NOV-2025'
			GROUP BY
				CC.SERVICE_CENTER_ID,
				O.HRMS_ORG_TITLE
),

/* ===========================
