	O.HRMS_ORGID = CC.SERVICE_CENTER_ID
LEFT JOIN CRM.JOBS J ON
	J.CUST_COMPLAIN_ID = CC.ID
	AND J.ID = (
	SELECT
		MAX(ID)
	FROM
		CRM.JOBS
	WHERE
		CUST_COMPLAIN_ID = CC.ID)
WHERE
	NVL(CC.TRANSFER_TYPE, 0) NOT IN ('REPLACEMENT_TRANSFER', 'LONG_TIME_UNDELIVERED')
		AND CC.ALKP_COMPLAIN_LEVEL_ID = 25
		AND NVL(J.ALKP_JOB_STATUS_ID, 0) IN (1316, 24, 41, 42)
			AND CC.PRODUCT_GROUP = NVL('', CC.PRODUCT_GROUP)
		GROUP BY
			CC.SERVICE_CENTER_ID,
			O.HRMS_ORG_TITLE
),

